"""Regenerate docs/data.js (the web demo's data) from the Python sources.

Usage: python tools/build_demo_data.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from copilot import code_refs  # noqa: E402

data = {
    "edition": code_refs.CODE_EDITION,
    "sections": code_refs.SECTIONS,
    "factors": {k: v[0] for k, v in code_refs.OCCUPANT_LOAD_FACTORS.items()},
    "travel": code_refs.TRAVEL_DISTANCE_LIMITS,
    "projects": [json.loads(p.read_text(encoding="utf-8")) for p in sorted((ROOT / "data" / "projects").glob("*.json"))],
    "gateCases": json.loads((ROOT / "evals" / "qa_gate_cases.json").read_text(encoding="utf-8")),
    "docPrompt": (ROOT / "copilot" / "doc_review_prompt.md").read_text(encoding="utf-8"),
    "docSchema": json.loads((ROOT / "copilot" / "doc_review_schema.json").read_text(encoding="utf-8")),
    "reviewTypes": json.loads((ROOT / "copilot" / "review_types.json").read_text(encoding="utf-8")),
    "recheckPrompt": (ROOT / "copilot" / "recheck_prompt.md").read_text(encoding="utf-8"),
    "recheckSchema": json.loads((ROOT / "copilot" / "recheck_schema.json").read_text(encoding="utf-8")),
    "sectionIndex": {k: v for k, v in json.loads((ROOT / "copilot" / "section_index.json").read_text(encoding="utf-8")).items() if not k.startswith("_")},
}
out = ROOT / "docs" / "data.js"
out.write_text("// Generated by tools/build_demo_data.py. Do not edit by hand.\nwindow.PRC_DATA = "
               + json.dumps(data, indent=1, ensure_ascii=False) + ";\n", encoding="utf-8")
# Cache-bust the page's scripts so browsers load the new version after each deploy.
import re, time  # noqa: E402
index = ROOT / "docs" / "index.html"
stamp = str(int(time.time()))
index.write_text(re.sub(r"(data|engine|review)\.js\?v=\d+", lambda m: f"{m.group(1)}.js?v={stamp}", index.read_text(encoding="utf-8")), encoding="utf-8")
print(f"wrote {out.relative_to(ROOT)} ({len(data['projects'])} projects), cache stamp {stamp}")
