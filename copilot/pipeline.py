from __future__ import annotations

import json
from pathlib import Path

from . import rules, senior_audit, qa_gate
from .models import ReviewResult


def load_project(path: str | Path) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def run(project: dict, use_llm: bool = False) -> ReviewResult:
    drafts = rules.review(project)
    if use_llm:
        from . import llm_reviewer

        drafts += llm_reviewer.review(project)
    audited, log = senior_audit.audit(drafts)
    accepted, rejected = qa_gate.gate(audited)
    return ReviewResult(project["id"], accepted, rejected, log)


def render_letter(project: dict, result: ReviewResult) -> str:
    lines = [
        f"# Plan Review Corrections — {project['name']}",
        "",
        f"Occupancy {project['occupancy']} · {'Sprinklered' if project.get('sprinklered') else 'Not sprinklered'} · "
        f"Estimated occupant load {rules.occupant_load(project)}",
        "",
    ]
    if not result.accepted:
        lines.append("No corrections. Plans appear to comply with the items checked.")
    for i, f in enumerate(result.accepted, 1):
        lines += [
            f"**{i}. [{f.severity}] {f.discipline} — Sheet {f.sheet} — {f.section}**",
            "",
            f"{f.comment}",
            "",
            f"_Basis: {f.evidence}_" if f.evidence else "",
            "",
        ]
    if result.rejected:
        lines += ["---", "", "## Held for human review (failed QA gate)", ""]
        for f, problems in result.rejected:
            lines.append(f"- `{f.check_id}` ({f.source}): {'; '.join(problems)}")
    lines += ["", "_Draft generated by Plan Review Copilot for a licensed reviewer to verify. Synthetic demo data._"]
    return "\n".join(lines)
